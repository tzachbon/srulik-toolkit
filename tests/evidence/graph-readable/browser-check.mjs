import { chromium } from 'playwright';
const url = process.argv[2], shots = process.argv[3];
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const errors = []; p.on('console', m => m.type() === 'error' && errors.push(m.text())); p.on('pageerror', e => errors.push(e.message));
let failed = 0;
const ok = (name, v, info = '') => { if (!v) failed++; console.log(`${v ? 'PASS' : 'FAIL'} ${name} ${info}`); };
try {
await p.goto(url); await p.click('[data-id="reresearch#0"]'); await p.waitForSelector('#pb dl.jobj');
const pb = p.locator('#pb');
ok('a rows', (await pb.locator('dl.jobj > dt').allInnerTexts()).join(',') === 'ready,questions,notes');
ok('a values', (await pb.locator('dl.jobj > dd').first().innerText()) === 'true' && (await pb.locator('dl.jobj > dd').nth(1).innerText()) === 'none');
const notes = pb.locator('dl.jobj > dd').nth(2);
ok('b heading', /Tested state/.test(await notes.locator('h4,h5,h6').first().innerText()));
ok('b list code+strong', await notes.locator('ul li code').count() >= 2 && (await notes.locator('ul li strong').innerText()) === '3f1c2ab');
ok('b table', await notes.locator('table tr').count() === 3, await notes.locator('table').innerText());
ok('c http link', (await notes.locator('a').getAttribute('href')) === 'https://example.com' && await notes.locator('a').count() === 1);
ok('c javascript stays text', (await notes.innerText()).includes('[bad](javascript:alert(1))') && await p.locator('a[href^="javascript"]').count() === 0);
ok('d raw closed', !(await pb.locator('details.raw').first().evaluate(d => d.open)));
await pb.locator('details.raw > summary').last().click();
ok('d raw json', /"ready": true/.test(await pb.locator('details.raw pre').last().innerText()));
await p.locator('#panel').screenshot({ path: `${shots}/panel-light.png` });
await pb.locator('details:has(summary:has-text("notes.md")) > summary').click();
await p.waitForSelector('#pb details .md ol');
const att = pb.locator('details:has(summary:has-text("notes.md"))');
ok('3 attachment', /How I checked/.test(await att.locator('h4').innerText()) && await att.locator('ol li').count() === 2 && await att.locator('blockquote').count() === 1);
await p.locator('#panel').screenshot({ path: `${shots}/panel-attachment.png` });
await p.click('#close'); await p.click('#theme'); await p.click('[data-id="reresearch#0"]'); await p.waitForSelector('#pb dl.jobj');
const [fg, bg] = await pb.evaluate(e => [getComputedStyle(e).color, getComputedStyle(e.closest('aside')).backgroundColor]);
ok('5 dark theme', fg !== bg && (await p.locator('html').getAttribute('data-theme')) === 'dark', `${fg} on ${bg}`);
await p.locator('#panel').screenshot({ path: `${shots}/panel-dark.png` });
await p.click('#close'); await p.click('#index'); await p.waitForSelector('#pb table');
ok('4 run index table', await p.locator('#pb table tr').count() === 2);
await p.locator('#panel').screenshot({ path: `${shots}/index.png` });
await p.setViewportSize({ width: 390, height: 844 }); await p.click('#close'); await p.click('[data-id="reresearch#0"]'); await p.waitForSelector('#pb dl.jobj');
ok('phone no horizontal overflow', await p.locator('#pb').evaluate(e => e.scrollWidth <= e.clientWidth + 1));
await p.locator('#panel').screenshot({ path: `${shots}/panel-phone.png` });
ok('6 console errors', errors.length === 0, errors.join(' | '));
} finally { await b.close(); }
if (failed) process.exitCode = 1;
